#=
# `PEPit.jl` tutorial: Gradient descent on smooth (possibly nonconvex) objectives

## Overview

This tutorial reproduces the example in
`examples/nonconvex_optimization/gradient_descent.jl` as a literate Julia script.

We use performance estimation programming (PEP) to compute the smallest constant
$\tau(n, L, \gamma)$ such that Equation @eq-gd-target holds for fixed-step gradient descent
on the class of $L$-smooth functions.

## Problem statement

We consider

$$
f_\star \triangleq \min_x f(x),
$$ {#eq-gd-objective}

where $f$ is $L$-smooth (without assuming convexity).

Our target guarantee is

$$
\min_{0 \le t \le n}\|f'(x_t)\|^2 \le \tau(n,L,\gamma)\,\bigl(f(x_0)-f(x_n)\bigr),
$$ {#eq-gd-target}

with iterates generated by fixed-step gradient descent.

## Algorithm

The iteration is

$$
x_{t+1}=x_t-\gamma f'(x_t), \qquad t=0,1,\dots,n-1,
$$ {#eq-gd-update}

which we encode symbolically in `PEPit.jl` through oracle calls and affine updates.
=#

