#=
## Sweep over iteration counts and plot the bound

To visualize how the guarantee evolves with the number of iterations $N$, we now sweep
over $N \in \{n_{\min},\dots,n_{\max}\}$ and compute both:

1. the PEPit coefficient $\tau_N$ returned by `wc_gradient_descent`, and
2. the theoretical coefficient $\frac{4L}{3N}$.

For each $N$, these coefficients satisfy

$$
\min_{0\le i\le N}\|f'(x_i)\|^2 \le \tau_N\,\bigl(f(x_0)-f(x_N)\bigr).
$$ {#eq-gd-sweep-coeff}

Because $\frac{4L}{3N}$ scales like $1/N$, we expect the theoretical curve to be strictly
decreasing as $N$ increases.
=#

function run_sweep_and_plot(; L=1.0, gamma=1.0, n_min=1, n_max=20, verbose=false) # sweep over $N$ values and plot PEPit vs theory coefficients
    @assert n_min >= 1 "n_min must be at least 1." # enforce valid lower bound for the iteration sweep
    @assert n_max >= n_min "n_max must be greater than or equal to n_min." # enforce an ordered sweep range

    n_values = collect(n_min:n_max) # build the grid of iteration counts $N$
    pepit_values = Vector{Float64}(undef, length(n_values)) # allocate storage for PEPit coefficients $\tau_N$
    theoretical_values = Vector{Float64}(undef, length(n_values)) # allocate storage for theoretical coefficients $4L/(3N)$

    for (idx, n_current) in pairs(n_values) # iterate through all sweep values with their array positions
        pepit_tau, theoretical_tau = wc_gradient_descent(L, gamma, n_current; verbose=verbose) # compute PEPit and theoretical coefficients at the current $N$
        pepit_values[idx] = pepit_tau # store the PEPit coefficient at index `idx`
        theoretical_values[idx] = theoretical_tau # store the theoretical coefficient at index `idx`
    end # finish computing all sweep values

    @assert length(n_values) == (n_max - n_min + 1) # verify the sweep length equals the requested integer interval size
    @assert length(pepit_values) == length(theoretical_values) == length(n_values) # verify all result arrays are aligned element-wise
    @assert all(diff(theoretical_values) .< 0) "Theoretical values must be strictly decreasing in n." # verify monotonic decay of the theoretical $1/N$ profile
    @assert all(isapprox.(theoretical_values, (4 / 3) * L ./ n_values; rtol=1e-12, atol=0.0)) # verify numerical consistency with $\frac{4L}{3N}$

    pepit_coords = collect(zip(n_values, pepit_values)) # package $(N,\tau_N^{\mathrm{PEPit}})$ points for plotting
    theory_coords = collect(zip(n_values, theoretical_values)) # package $(N,\tau_N^{\mathrm{theory}})$ points for plotting

    @pgf axis = Axis( # build a PGFPlots axis object containing both curves
        { # configure axis-level display options
            width = "13.5cm", # set plot width
            height = "8.3cm", # set plot height
            title = "Gradient Descent on Smooth Nonconvex Functions", # set plot title
            xlabel = L"Number of Iterations $N$", # label the horizontal axis by iteration count
            ylabel = L"Worst-case coefficient $\tau_N$ for $\min_{i\leq N}\|f'(x_i)\|^2$", # label the vertical axis with the correct metric coefficient
            legend_pos = "north east", # place legend in the upper-right corner
            axis_lines = "box", # draw full boxed axes
        }, # end axis configuration
        PlotInc( # add the PEPit curve
            { # configure line appearance for the PEPit curve
                color = "{rgb,255:red,11;green,114;blue,133}", # set PEPit curve color
                mark = "o", # use circular markers for PEPit points
                line_width = "3pt", # set PEPit line thickness
            }, # end PEPit appearance configuration
            Coordinates(pepit_coords), # pass PEPit coordinate data
        ), # end PEPit plot component
        LegendEntry(L"$\texttt{PEPit.jl}$ Bound"), # add legend label for the PEPit curve
        PlotInc( # add the theoretical curve
            { # configure line appearance for the theoretical curve
                color = "{rgb,255:red,230;green,119;blue,0}", # set theoretical curve color
                "no marks", # disable point markers for the theoretical curve
                line_width = "2pt", # set theoretical line thickness
            }, # end theoretical appearance configuration
            Coordinates(theory_coords), # pass theoretical coordinate data
        ), # end theoretical plot component
        LegendEntry(L"\textrm{Theoretical Bound}"), # add legend label for the theoretical curve
    ) # finish constructing the axis object

    picture = TikzPicture(axis) # wrap the axis into a TikZ picture for saving

    output_base = joinpath(@__DIR__, "gradient_descent_pepit_vs_theory_n$(n_min)_n$(n_max)") # define base output path in the tutorial directory
    tex_path = output_base * ".tex" # construct path for TikZ/TeX output
    png_path = output_base * ".png" # construct path for PNG output
    pdf_path = output_base * ".pdf" # construct path for PDF output

    pgfsave(tex_path, picture) # save TeX output unconditionally
    pgfsave(pdf_path, picture) # save PDF output unconditionally
    png_saved = false # initialize flag tracking whether PNG export succeeds
    try # attempt optional PNG export
        pgfsave(png_path, picture) # save PNG output if backend support is available
        png_saved = true # mark PNG export as successful
    catch err # handle PNG export failure without interrupting the tutorial run
        println("Warning: PNG export failed ($(sprint(showerror, err))). Continuing with TEX/PDF outputs.") # report PNG failure while preserving successful TeX/PDF outputs
    end # close PNG export error-handling block

    println("Saved plot (TEX): ", tex_path) # print TeX artifact path
    println("Saved plot (PDF): ", pdf_path) # print PDF artifact path
    if png_saved # branch on PNG export status
        println("Saved plot (PNG): ", png_path) # print PNG artifact path when available
    else # otherwise report PNG omission
        println("PNG plot was not saved.") # inform that PNG was skipped or failed
    end # close PNG status branch
    println("PEPit values: first=", pepit_values[1], ", last=", pepit_values[end]) # summarize endpoint values of the PEPit curve
    println("Theoretical values: first=", theoretical_values[1], ", last=", theoretical_values[end]) # summarize endpoint values of the theoretical curve

    return n_values, pepit_values, theoretical_values, png_path, pdf_path # return sweep data and output paths for downstream use
end # close the sweep-and-plot helper function

