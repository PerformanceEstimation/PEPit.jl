using PEPit # import PEPit types and modeling routines
using OrderedCollections # import OrderedDict for parameter passing
using Clarabel # import Clarabel optimizer backend for conic SDP solving
using PGFPlotsX, LaTeXStrings # import plotting backend and LaTeX-friendly strings for axis labels

#=
## Function: `wc_gradient_descent`

### What this function computes

For given $(L,\gamma,n)$, this routine builds and solves a PEP whose objective is the minimum
recorded gradient norm squared along the trajectory, normalized by
$f(x_0)-f(x_n)\le 1$. The returned `PEPit_tau` is the worst-case value of that metric.

For comparison, we also compute the standard reference value

$$
\tau_{\mathrm{theory}} = \frac{4}{3}\frac{L}{n},
$$ {#eq-gd-theory}

and report both numbers.
=#

function wc_gradient_descent(L, gamma, n; verbose=true) # build and solve the worst-case PEP for fixed-step GD
    problem = PEP() # instantiate an empty performance estimation problem

    param = OrderedDict("L" => L) # store smoothness metadata for the declared function class
    func = declare_function!(problem, SmoothFunction, param; reuse_gradient=true) # declare an $L$-smooth function with reusable gradients

    x0 = set_initial_point!(problem) # create symbolic initial iterate $x_0$
    g0, f0 = oracle!(func, x0) # query $(f'(x_0), f(x_0))$ from the oracle model

    x = x0 # initialize current iterate to $x_0$
    gx, fx = g0, f0 # initialize current oracle pair to iteration $t=0$
    set_performance_metric!(problem, gx^2) # register $\|f'(x_0)\|^2$ as a candidate for the final minimum

    for i in 1:n # execute $n$ fixed-step gradient iterations
        x = x - gamma * gx # apply $x_{t+1}=x_t-\gamma f'(x_t)$
        gx, fx = oracle!(func, x) # evaluate $(f'(x_i), f(x_i))$ at the new iterate
        set_performance_metric!(problem, gx^2) # register $\|f'(x_i)\|^2$ so the model minimizes over all recorded steps
    end # finish the gradient descent loop

    set_initial_condition!(problem, f0 - fx <= 1) # impose normalization $f(x_0)-f(x_n)\le 1$

    PEPit_tau = solve!(problem; solver=Clarabel.Optimizer, verbose=verbose) # solve the SDP with Clarabel and recover the worst-case constant

    theoretical_tau = 4 / 3 * L / n # compute Equation @eq-gd-theory for baseline comparison

    if verbose # print a textual comparison when requested
        println("*** Example file: worst-case performance of gradient descent with fixed step-size ***") # print experiment title
        println("\tPEPit guarantee:\t min_i ||f'(x_i)||^2 <= $(round(PEPit_tau, digits=6)) (f(x_0)-f_*)") # display PEP-computed guarantee
        println("\tTheoretical guarantee:\t min_i ||f'(x_i)||^2 <= $(round(theoretical_tau, digits=6)) (f(x_0)-f_*)") # display theoretical guarantee
    end # close the verbose-printing branch

    return PEPit_tau, theoretical_tau # return both the computed and baseline constants
end # close function definition

